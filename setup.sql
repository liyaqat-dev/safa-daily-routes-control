-- ============================================================================
-- SAFA SCHEDULE DASHBOARD - ROLLING 3-DAY SCHEMA (SUPABASE POSTGRESQL)
-- ============================================================================

DROP TABLE IF EXISTS public.safa_daily_routes CASCADE;

CREATE TABLE public.safa_daily_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_name TEXT NOT NULL,
    route_date DATE NOT NULL,
    route TEXT,
    type TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(person_name, route_date)
);

ALTER TABLE public.safa_daily_routes ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read access" ON public.safa_daily_routes FOR SELECT USING (true);
CREATE POLICY "Allow public insert access" ON public.safa_daily_routes FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update access" ON public.safa_daily_routes FOR UPDATE USING (true);
CREATE POLICY "Allow public delete access" ON public.safa_daily_routes FOR DELETE USING (true);

ALTER PUBLICATION supabase_realtime ADD TABLE public.safa_daily_routes;

-- 5. Create Display Config Table for TV Syncing
DROP TABLE IF EXISTS public.display_config CASCADE;
CREATE TABLE public.display_config (
    id INT PRIMARY KEY DEFAULT 1,
    is_filtered BOOLEAN DEFAULT false,
    name_filter TEXT DEFAULT '',
    route_filter TEXT DEFAULT '',
    type_filter TEXT DEFAULT '',
    date_filter TEXT DEFAULT '',
    display_days INT DEFAULT 3,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Enable RLS and Realtime for Display Config
ALTER TABLE public.display_config ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read access config" ON public.display_config FOR SELECT USING (true);
CREATE POLICY "Allow public update access config" ON public.display_config FOR UPDATE USING (true);
CREATE POLICY "Allow public insert access config" ON public.display_config FOR INSERT WITH CHECK (true);

ALTER PUBLICATION supabase_realtime ADD TABLE public.display_config;

